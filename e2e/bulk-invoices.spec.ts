import { clickMenuLink } from './navigation';
import { expect, test } from '@playwright/test';

test('a tenant previews, downloads, and confirms a monthly bulk invoice run only once', async ({ page }) => {
  const contractName = `Bulk billing acceptance ${Date.now()}`;
  await page.goto('/');
  await page.getByLabel('Demo identity').selectOption('nexio-admin');
  await page.getByRole('button', { name: 'Enter demo' }).click();
  await clickMenuLink(page, 'Master Data', 'Contracts');
  await page.getByRole('button', { name: 'Add contract' }).click();
  await page.getByLabel('Contract name').fill(contractName);
  await page.getByLabel('Customer').selectOption({ index: 1 });
  await page.getByLabel('Start date').fill('2026-01-01');
  await page.getByLabel('End date').fill('2026-12-31');
  await page.getByLabel('Contract value').fill('1000');
  await page.getByLabel('Select services').click();
  await page.getByRole('group', { name: 'Services' }).getByRole('checkbox').first().check();
  await page.getByLabel('Select services').click();
  await page.getByRole('button', { name: 'Create contract' }).click();
  await expect(page.getByText(contractName, { exact: true })).toBeVisible();
  await clickMenuLink(page, 'Operational Records', 'Additional Services');
  await page.getByRole('button', { name: 'Add additional service' }).click();
  await expect(page.getByLabel('Additional service customer', { exact: true })).toBeVisible();
  await page.getByLabel('Additional service customer', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Additional service contract').selectOption({ label: contractName });
  await page.getByLabel('Additional service date').fill('2026-10-15');
  await page.getByLabel('Customized price').fill('250');
  await page.getByLabel('Service description').fill('Bulk run workshop');
  await page.getByRole('button', { name: 'Add additional service' }).last().click();

  await page.goto('/invoices');
  await page.getByRole('button', { name: 'Bulk invoice run' }).click();
  const dialog = page.getByRole('dialog', { name: 'Bulk invoice run' });
  await expect(dialog).toBeVisible();
  await expect(page).toHaveURL(/\/invoices\/bulk$/);
  await dialog.getByLabel('Billing period').selectOption('2026-10');
  await dialog.getByRole('button', { name: 'Preview invoices' }).click();
  await expect(dialog.getByText(contractName)).toBeVisible();
  await expect(dialog.getByText('Bulk run workshop')).toBeVisible();
  const download = page.waitForEvent('download');
  await dialog.getByRole('link', { name: 'Download preview' }).click();
  await expect((await download).suggestedFilename()).toBe('bulk-invoice-preview-2026-10.pdf');
  await dialog.getByRole('button', { name: 'Issue reviewed invoices' }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Issue invoices' }).click();
  await expect(dialog.getByText(/Issued \d+ invoices?\./)).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Invoice register' })).toBeVisible();
  await expect(page.getByRole('row', { name: new RegExp(contractName) })).toBeVisible();
  await dialog.getByRole('button', { name: 'Issue reviewed invoices' }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Issue invoices' }).click();
  await expect(dialog.getByText('This billing period was already issued.')).toBeVisible();
  await dialog.getByRole('button', { name: 'Close bulk invoice run' }).click();
  await expect(dialog).toBeHidden();
  await expect(page).toHaveURL(/\/invoices$/);
  await page.goto('/invoices/bulk');
  await expect(page.getByRole('dialog', { name: 'Bulk invoice run' })).toBeVisible();
  await page.getByRole('button', { name: 'Close bulk invoice run' }).click();
  await expect(page).toHaveURL(/\/invoices$/);
});
