import { expect, test } from '@playwright/test';
import { demoOrigin } from './test-ports';

const SELLER_GSTIN = '29AAGCB7383J1Z4';
let originalSettings: Record<string, unknown> | undefined;

test.afterEach(async ({ playwright }) => {
  if (!originalSettings) return;
  const request = await playwright.request.newContext({ baseURL: demoOrigin, extraHTTPHeaders: { Origin: demoOrigin } });
  await request.post('/api/auth/demo-login', { data: { userId: 'nexio-admin' } });
  await request.put('/api/settings', { data: originalSettings });
  await request.dispose();
  originalSettings = undefined;
});

test('invoice dialog adds and removes rows, calculates GST per row, and persists details', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Demo identity').selectOption('nexio-admin');
  await page.getByRole('button', { name: 'Enter demo' }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  originalSettings = (await (await page.request.get('/api/settings')).json() as { settings: Record<string, unknown> }).settings;
  expect((await page.request.put('/api/settings', { data: { ...originalSettings, gstin: SELLER_GSTIN } })).ok()).toBeTruthy();
  const customerResponse = await page.request.get('/api/customers?pageSize=100');
  expect(customerResponse.ok(), await customerResponse.text()).toBeTruthy();
  const { items: customers } = await customerResponse.json() as { items: Array<{ id: string; gstin: string }> };
  const contractResponse = await page.request.get('/api/contracts?pageSize=100');
  const { items: contracts } = await contractResponse.json() as { items: Array<{ id: string; customerId: string; status: string }> };
  const firstActive = contracts.find((contract) => contract.status === 'active' && customers.some((customer) => customer.id === contract.customerId && customer.gstin));
  const customer = customers.find((item) => item.id === firstActive?.customerId);
  expect(customer).toBeDefined();
  await page.goto('/invoices');
  await page.getByRole('button', { name: 'Add invoice' }).click();
  const dialog = page.getByRole('dialog', { name: 'Create invoice' });
  await dialog.getByRole('combobox', { name: /^Customer \*/ }).selectOption(customer!.id);
  const contractSelect = dialog.getByLabel('Contract (optional)');
  await expect(contractSelect).toHaveValue(firstActive!.id);
  await contractSelect.selectOption('');
  await expect(contractSelect).toHaveValue('');
  await expect(dialog.getByLabel('Venue')).toHaveCount(0);
  await dialog.getByLabel('Description 1').fill('Hall rental');
  await dialog.getByLabel('Quantity 1').fill('2');
  await dialog.getByLabel('Rate 1').fill('100');
  await expect(dialog.getByLabel('Tax type 1')).toHaveValue('cgst_sgst');
  await dialog.getByLabel('HSN/SAC 1').fill('998311');
  await dialog.getByLabel('GST percent 1').fill('18');
  await dialog.getByRole('button', { name: 'Add Line' }).click();
  await dialog.getByLabel('Description 2').fill('Security deposit');
  await dialog.getByLabel('Rate 2').fill('50');
  await dialog.getByLabel('Tax type 2').selectOption('none');
  await dialog.getByRole('button', { name: 'Add Line' }).click();
  await dialog.getByLabel('Description 3').fill('Remove me');
  await dialog.getByLabel('Rate 3').fill('100');
  await dialog.getByRole('button', { name: 'Remove' }).nth(2).click();
  await expect(dialog.getByLabel('Description 3')).toHaveCount(0);
  await expect(dialog.locator('.invoice-totals')).toContainText('₹286.00');
  await dialog.getByLabel('Notes').fill('Security deposit is refundable');
  await dialog.getByRole('button', { name: 'Create Invoice' }).click();
  await expect(dialog).toBeHidden();
  const invoiceResponse = await page.request.get('/api/invoices?pageSize=100');
  const { items: invoices } = await invoiceResponse.json() as { items: Array<{ id: string; snapshot: { venue?: string; notes?: string; lines?: Array<{ description: string; gstRate: number }> }; taxableMinor: number; gstMinor: number; totalMinor: number }> };
  const created = invoices.find((item) => item.snapshot.notes === 'Security deposit is refundable');
  expect(created?.snapshot.venue).toBeFalsy();
  expect(created).toMatchObject({ taxableMinor: 25000, gstMinor: 3600, totalMinor: 28600, snapshot: { lines: [{ description: 'Hall rental', gstRate: 18 }, { description: 'Security deposit', gstRate: 0 }] } });
  await page.goto(`/invoices/${created!.id}`);
  await expect(page.getByRole('heading', { name: 'Line items' })).toBeVisible();
  await expect(page.getByRole('row', { name: /Hall rental/ })).toContainText('₹236.00');
});

test('invoice dialog creates a customer from the customer source selector', async ({ page }) => {
  const marker = `Invoice customer ${Date.now()}`;
  await page.goto('/');
  await page.getByLabel('Demo identity').selectOption('nexio-admin');
  await page.getByRole('button', { name: 'Enter demo' }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto('/invoices');
  await page.getByRole('button', { name: 'Add invoice' }).click();
  const dialog = page.getByRole('dialog', { name: 'Create invoice' });
  await dialog.getByLabel('Customer Source').selectOption('new');
  await dialog.getByLabel('Customer / company name').fill(marker);
  await dialog.getByLabel('Contact name').fill('Billing Manager');
  await dialog.getByLabel('Phone').fill('9999999999');
  await dialog.getByLabel('Email').fill(`invoice-${Date.now()}@example.test`);
  await expect(dialog.getByLabel('Venue')).toHaveCount(0);
  await dialog.getByLabel('Billing Address').fill('Hall 1, Bengaluru');
  await expect(dialog.getByLabel('GST Applicable')).toBeDisabled();
  await expect(dialog.getByLabel('GST Applicable')).not.toBeChecked();
  await dialog.getByLabel('Description 1').fill('Deposit');
  await dialog.getByLabel('Rate 1').fill('250');
  await dialog.getByRole('button', { name: 'Create Invoice' }).click();
  await expect(dialog).toBeHidden();
  const response = await page.request.get(`/api/invoices?search=${encodeURIComponent(marker)}`);
  const { items } = await response.json() as { items: Array<{ customerName: string; totalMinor: number }> };
  expect(items).toEqual([expect.objectContaining({ customerName: marker, totalMinor: 25000 })]);
});
